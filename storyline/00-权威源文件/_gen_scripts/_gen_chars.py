# ---------- 从 guide 按标题抽取章节 ----------
def extract_block(text, start_marker, end_marker):
    """抽取 start_marker 行（含）到 end_marker 行（不含）之间的内容。"""
    lines = text.splitlines()
    out, capturing = [], False
    for ln in lines:
        if start_marker in ln:
            capturing = True
            out.append(ln)
            continue
        if capturing and end_marker in ln:
            break
        if capturing:
            out.append(ln)
    return "\n".join(out).strip() + "\n"

# 单角色块（### 级，取到下一个 ### 之前）
def extract_char(text, marker):
    lines = text.splitlines()
    out, cap = [], False
    for ln in lines:
        if marker in ln and ln.strip().startswith("###"):
            cap = True
            out.append(ln)
            continue
        if cap and ln.strip().startswith("###") and marker not in ln:
            break
        if cap:
            out.append(ln)
    return "\n".join(out).strip() + "\n"

